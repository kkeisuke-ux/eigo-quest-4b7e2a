export interface AlphabetItem {
  letter: string
  kind: 'upper' | 'lower'
  /** SVGパス（1画=1パス、書き順の順） */
  strokes: string[]
  audio: {
    /** 文字名としてTTSへ渡す文字列（例: "A"） */
    name: string
    /** フォニックス音（将来追加。例: "ah"）。未設定ならフォニックス再生は不可 */
    phonics?: string
  }
}

const U = (letter: string, strokes: string[]): AlphabetItem => ({
  letter,
  kind: 'upper',
  strokes,
  audio: { name: letter },
})

const L = (letter: string, strokes: string[]): AlphabetItem => ({
  letter,
  kind: 'lower',
  strokes,
  audio: { name: letter.toUpperCase() },
})

